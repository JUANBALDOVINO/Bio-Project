-- BioMant · Tecnovigilancia · Etapa 2: cuarentena, bloqueo y trazabilidad de liberación
-- Ejecutar después de supabase_tecnovigilancia_etapa1.sql.

CREATE TABLE IF NOT EXISTS public.tecnovigilancia_bloqueos (
  id_bloqueo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE RESTRICT,
  id_reporte bigint NOT NULL REFERENCES public.reportes_tecnovigilancia(id_reporte) ON DELETE RESTRICT,
  estado_previo varchar(40) NOT NULL,
  activo boolean NOT NULL DEFAULT true,
  motivo_bloqueo text NOT NULL DEFAULT 'Cuarentena preventiva por reporte de tecnovigilancia',
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  liberado_por integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  nombre_liberador varchar(100),
  estado_final varchar(40),
  motivo_liberacion text,
  liberado_en timestamptz,
  CHECK (NOT activo OR (liberado_en IS NULL AND estado_final IS NULL)),
  CHECK (activo OR (liberado_en IS NOT NULL AND motivo_liberacion IS NOT NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_tecnovigilancia_bloqueo_equipo_activo
  ON public.tecnovigilancia_bloqueos(id_equipo) WHERE activo;
CREATE INDEX IF NOT EXISTS idx_tecnovigilancia_bloqueos_reporte
  ON public.tecnovigilancia_bloqueos(id_reporte, creado_en DESC);

ALTER TABLE public.tecnovigilancia_bloqueos ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.tecnovigilancia_bloqueos IS
  'Bloqueos preventivos de equipos por tecnovigilancia. Se liberan solo por un Administrador y conservan el estado previo y la trazabilidad.';

-- Recupera casos abiertos creados en la etapa 1: también quedan en cuarentena.
WITH casos_abiertos AS (
  SELECT DISTINCT ON (t.id_equipo)
         t.id_equipo, t.id_reporte, e.estado AS estado_previo
  FROM public.reportes_tecnovigilancia t
  JOIN public.equipos e ON e.id_equipo = t.id_equipo
  WHERE t.estado IN ('reportado', 'en_investigacion')
  ORDER BY t.id_equipo, t.creado_en, t.id_reporte
)
INSERT INTO public.tecnovigilancia_bloqueos (id_equipo, id_reporte, estado_previo)
SELECT c.id_equipo, c.id_reporte, c.estado_previo
FROM casos_abiertos c
WHERE NOT EXISTS (
  SELECT 1 FROM public.tecnovigilancia_bloqueos b
  WHERE b.id_equipo = c.id_equipo AND b.activo
);

UPDATE public.equipos e
SET estado = 'Fuera de servicio'
WHERE EXISTS (
  SELECT 1 FROM public.tecnovigilancia_bloqueos b
  WHERE b.id_equipo = e.id_equipo AND b.activo
);
