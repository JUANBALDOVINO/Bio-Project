-- Esquema PostgreSQL equivalente a la base BioMant de XAMPP.
-- Ejecutar en un proyecto Supabase nuevo (o con tablas vacías).

CREATE TABLE IF NOT EXISTS public.equipos (
  id_equipo varchar(30) PRIMARY KEY,
  nombre_equipo varchar(100) NOT NULL,
  marca varchar(50) NOT NULL,
  modelo varchar(50) NOT NULL,
  numero_serie varchar(50) NOT NULL,
  nivel_riesgo varchar(20) NOT NULL,
  ubicacion varchar(50) NOT NULL,
  estado varchar(20) NOT NULL,
  tipo_categoria varchar(20) NOT NULL,
  fecha_compra date,
  horas_uso integer DEFAULT 0,
  foto_equipo varchar(255),
  hist_mto_preventivo text,
  fecha_mto_preventivo date,
  hist_mto_correctivo text,
  fecha_mto_correctivo date,
  proximo_mto_preventivo date
);

CREATE TABLE IF NOT EXISTS public.usuarios (
  id_usuario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  correo varchar(150) NOT NULL UNIQUE,
  password varchar(255) NOT NULL,
  rol varchar(20) NOT NULL DEFAULT 'Tecnico' CHECK (rol IN ('Administrador', 'Tecnico')),
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.mantenimientos (
  id_mantenimiento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE CASCADE,
  tipo varchar(20) NOT NULL CHECK (tipo IN ('Preventivo', 'Correctivo')),
  fecha date NOT NULL,
  detalle text NOT NULL,
  modalidad_servicio varchar(16) NOT NULL DEFAULT 'Interno' CHECK (modalidad_servicio IN ('Interno', 'Externo')),
  empresa_contratista varchar(160),
  tecnico_contratista varchar(120),
  orden_servicio varchar(80),
  fecha_programada_atendida date,
  id_usuario integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.notificaciones_mantenimiento (
  id_notificacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE CASCADE,
  fecha_programada date NOT NULL,
  estado_alerta varchar(20) NOT NULL CHECK (estado_alerta IN ('proximo', 'vencido')),
  enviado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_equipo, fecha_programada, estado_alerta)
);

CREATE TABLE IF NOT EXISTS public.notificaciones_mantenimiento_destinatarios (
  id_envio bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE CASCADE,
  fecha_programada date NOT NULL,
  estado_alerta varchar(20) NOT NULL CHECK (estado_alerta IN ('proximo', 'vencido')),
  dias_alerta integer NOT NULL DEFAULT 0,
  correo_destinatario varchar(254) NOT NULL,
  enviado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (id_equipo, fecha_programada, estado_alerta, dias_alerta, correo_destinatario)
);

CREATE TABLE IF NOT EXISTS public.reprogramaciones_mantenimiento_preventivo (
  id_reprogramacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE RESTRICT,
  fecha_anterior date NOT NULL,
  fecha_nueva date NOT NULL,
  motivo varchar(600) NOT NULL,
  id_usuario integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  nombre_usuario varchar(100) NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT reprogramacion_rango CHECK (fecha_nueva > fecha_anterior AND fecha_nueva <= fecha_anterior + 7)
);
CREATE INDEX IF NOT EXISTS idx_reprogramaciones_equipo_fecha ON public.reprogramaciones_mantenimiento_preventivo(id_equipo, creado_en DESC);

CREATE INDEX IF NOT EXISTS idx_mant_equipo ON public.mantenimientos(id_equipo);
CREATE INDEX IF NOT EXISTS idx_mant_fecha ON public.mantenimientos(fecha);
CREATE INDEX IF NOT EXISTS idx_alerta_destinatario_correo ON public.notificaciones_mantenimiento_destinatarios(correo_destinatario);

-- BioMant connects through its private backend; block direct Data API access.
ALTER TABLE public.equipos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mantenimientos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notificaciones_mantenimiento ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notificaciones_mantenimiento_destinatarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reprogramaciones_mantenimiento_preventivo ENABLE ROW LEVEL SECURITY;
