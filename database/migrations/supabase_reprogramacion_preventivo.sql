-- BioMant: reprogramación justificada del mantenimiento preventivo.
-- Ejecutar una sola vez en Supabase SQL Editor.
CREATE TABLE IF NOT EXISTS public.reprogramaciones_mantenimiento_preventivo (
  id_reprogramacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE RESTRICT,
  fecha_anterior date NOT NULL,
  fecha_nueva date NOT NULL,
  motivo varchar(600) NOT NULL CHECK (char_length(trim(motivo)) >= 10),
  id_usuario integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  nombre_usuario varchar(100) NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT reprogramacion_preventivo_rango CHECK (fecha_nueva > fecha_anterior AND fecha_nueva <= fecha_anterior + 7)
);
CREATE INDEX IF NOT EXISTS idx_reprogramaciones_preventivo_equipo_fecha
  ON public.reprogramaciones_mantenimiento_preventivo (id_equipo, creado_en DESC);
ALTER TABLE public.reprogramaciones_mantenimiento_preventivo ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.reprogramaciones_mantenimiento_preventivo IS
  'Historial inmutable de reprogramaciones justificadas de mantenimiento preventivo.';
