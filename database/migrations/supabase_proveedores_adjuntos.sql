-- BioMant: metadatos de los archivos recibidos en órdenes de trabajo externas.
-- Ejecutar en Supabase SQL Editor después de supabase_proveedores_ordenes.sql.
-- Los archivos se almacenan en el bucket privado de Supabase Storage
-- biomant-ordenes-informes, que el servidor crea al recibir el primer adjunto.

CREATE TABLE IF NOT EXISTS public.ordenes_trabajo_archivos (
    id_archivo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden bigint NOT NULL
        REFERENCES public.ordenes_trabajo_externas(id_orden) ON DELETE CASCADE,
    ruta_storage text NOT NULL UNIQUE,
    nombre_archivo varchar(180) NOT NULL,
    tipo_mime varchar(127) NOT NULL,
    tamano_bytes bigint NOT NULL CHECK (tamano_bytes > 0 AND tamano_bytes <= 20971520),
    subido_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ordenes_trabajo_archivos_orden
    ON public.ordenes_trabajo_archivos(id_orden, subido_en DESC);

ALTER TABLE public.ordenes_trabajo_archivos ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.ordenes_trabajo_archivos IS
    'Metadatos de adjuntos de órdenes externas; el contenido está en un bucket privado y se sirve mediante URLs firmadas.';
