-- BioMant: proveedores externos y órdenes de trabajo con enlace de acceso.
CREATE TABLE IF NOT EXISTS public.proveedores_externos (
 id_proveedor bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa varchar(160) NOT NULL,
 correo varchar(254) NOT NULL,
 telefono varchar(40),
 servicios text,
 activo boolean NOT NULL DEFAULT true,
 creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.proveedor_equipos (
 id_proveedor bigint NOT NULL REFERENCES public.proveedores_externos(id_proveedor) ON DELETE CASCADE,
 id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE CASCADE,
 PRIMARY KEY(id_proveedor,id_equipo)
);
CREATE TABLE IF NOT EXISTS public.ordenes_trabajo_externas (
 id_orden bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_proveedor bigint NOT NULL REFERENCES public.proveedores_externos(id_proveedor) ON DELETE RESTRICT,
 id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE RESTRICT,
 tipo varchar(16) NOT NULL CHECK(tipo IN ('Preventivo','Correctivo')),
 descripcion text NOT NULL,
 protocolo text,
 token_hash char(64) NOT NULL UNIQUE,
 estado varchar(24) NOT NULL DEFAULT 'enviada' CHECK(estado IN ('enviada','aceptada','en_proceso','completada','cerrada')),
 vence_en timestamptz NOT NULL,
 informe_proveedor text,
 creado_por integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
 creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_ot_externas_creadas ON public.ordenes_trabajo_externas(creado_en DESC);
ALTER TABLE public.proveedores_externos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.proveedor_equipos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ordenes_trabajo_externas ENABLE ROW LEVEL SECURITY;
