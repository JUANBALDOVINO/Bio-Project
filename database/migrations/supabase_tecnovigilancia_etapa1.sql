-- BioMant · Tecnovigilancia · Etapa 1: recepción y trazabilidad del reporte
-- Migración aditiva para el proyecto Supabase existente. No elimina ni modifica
-- tablas de inventario, usuarios o mantenimiento.

CREATE TABLE IF NOT EXISTS public.reportes_tecnovigilancia (
  id_reporte bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_equipo varchar(30) NOT NULL REFERENCES public.equipos(id_equipo) ON UPDATE CASCADE ON DELETE RESTRICT,
  tipo_reporte varchar(32) NOT NULL CHECK (tipo_reporte IN (
    'evento_adverso_serio', 'evento_adverso_no_serio', 'incidente_adverso'
  )),
  fecha_evento timestamptz NOT NULL,
  lugar_evento varchar(200) NOT NULL,
  descripcion text NOT NULL,
  consecuencias text NOT NULL,
  acciones_inmediatas text NOT NULL,
  id_reportante integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  nombre_reportante varchar(100) NOT NULL,
  persona_manejaba varchar(150),
  cargo_persona_manejaba varchar(120),
  persona_presente varchar(16) NOT NULL DEFAULT 'desconocido'
    CHECK (persona_presente IN ('si', 'no', 'desconocido')),
  estado varchar(24) NOT NULL DEFAULT 'reportado'
    CHECK (estado IN ('reportado', 'en_investigacion', 'cerrado', 'descartado')),
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (char_length(btrim(lugar_evento)) BETWEEN 2 AND 200),
  CHECK (char_length(btrim(descripcion)) BETWEEN 10 AND 10000),
  CHECK (char_length(btrim(consecuencias)) BETWEEN 2 AND 5000),
  CHECK (char_length(btrim(acciones_inmediatas)) BETWEEN 2 AND 5000),
  CHECK (persona_manejaba IS NULL OR char_length(btrim(persona_manejaba)) <= 150),
  CHECK (cargo_persona_manejaba IS NULL OR char_length(btrim(cargo_persona_manejaba)) <= 120)
);

CREATE TABLE IF NOT EXISTS public.tecnovigilancia_auditoria (
  id_evento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reporte bigint NOT NULL REFERENCES public.reportes_tecnovigilancia(id_reporte) ON DELETE RESTRICT,
  id_usuario integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  nombre_usuario varchar(100) NOT NULL,
  accion varchar(40) NOT NULL,
  datos jsonb NOT NULL DEFAULT '{}'::jsonb,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tecnovigilancia_equipo_fecha
  ON public.reportes_tecnovigilancia(id_equipo, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_tecnovigilancia_estado_fecha
  ON public.reportes_tecnovigilancia(estado, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_tecnovigilancia_tipo_fecha
  ON public.reportes_tecnovigilancia(tipo_reporte, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_tecnovigilancia_auditoria_reporte
  ON public.tecnovigilancia_auditoria(id_reporte, creado_en);

ALTER TABLE public.reportes_tecnovigilancia ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tecnovigilancia_auditoria ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.reportes_tecnovigilancia IS
  'Reportes iniciales de tecnovigilancia. El acceso se realiza desde el backend privado de BioMant.';
COMMENT ON TABLE public.tecnovigilancia_auditoria IS
  'Bitácora de eventos de tecnovigilancia; la aplicación solo agrega filas y no ofrece edición ni borrado.';

