-- BioMant · Auditoría general · Etapa 1
-- Tabla append-only para registrar acciones de los módulos de la aplicación.

CREATE TABLE IF NOT EXISTS public.auditoria_eventos (
  id_evento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario integer REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
  nombre_usuario varchar(100) NOT NULL,
  rol_usuario varchar(20),
  modulo varchar(40) NOT NULL,
  accion varchar(60) NOT NULL,
  entidad varchar(60) NOT NULL,
  id_entidad varchar(120),
  resumen varchar(300) NOT NULL,
  valores_anteriores jsonb NOT NULL DEFAULT '{}'::jsonb,
  valores_nuevos jsonb NOT NULL DEFAULT '{}'::jsonb,
  metadatos jsonb NOT NULL DEFAULT '{}'::jsonb,
  creado_en timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_auditoria_eventos_fecha
  ON public.auditoria_eventos(creado_en DESC, id_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_eventos_usuario_fecha
  ON public.auditoria_eventos(id_usuario, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_eventos_modulo_fecha
  ON public.auditoria_eventos(modulo, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_eventos_entidad
  ON public.auditoria_eventos(entidad, id_entidad);

ALTER TABLE public.auditoria_eventos ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.auditoria_eventos IS
  'Bitácora general de BioMant. Las escrituras y lecturas se realizan exclusivamente desde el backend autenticado.';

REVOKE ALL ON TABLE public.auditoria_eventos FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.auditoria_eventos_id_evento_seq FROM anon, authenticated;
